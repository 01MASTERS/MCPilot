#!/usr/bin/env bash
# generate-prod-secrets.sh
# Generates high-entropy cryptographic secrets for MCPilot production deployment (INFRA-06)

set -euo pipefail

OUTPUT_FILE="${1:-secrets-prod.yaml}"

echo "======================================================="
echo "  MCPilot — Production Secret Generator (INFRA-06)"
echo "  Target output: ${OUTPUT_FILE}"
echo "======================================================="

# Helper for random base64 strings
rand_secret() {
  node -e "console.log(require('crypto').randomBytes(24).toString('hex'))"
}

MARIADB_ROOT_PASS=$(rand_secret)
MARIADB_PASS=$(rand_secret)
WP_ADMIN_PASS=$(rand_secret)
JWT_SECRET=$(rand_secret)
WC_CONSUMER_KEY="ck_$(rand_secret)"
WC_CONSUMER_SECRET="cs_$(rand_secret)"

cat <<EOF > "${OUTPUT_FILE}"
# AUTOGENERATED PRODUCTION SECRETS — DO NOT COMMIT TO VERSION CONTROL
apiVersion: v1
kind: Secret
metadata:
  name: mcpilot-secrets
  namespace: default
  labels:
    app.kubernetes.io/name: mcpilot
    app.kubernetes.io/component: secrets
type: Opaque
stringData:
  mariadb-root-password: "${MARIADB_ROOT_PASS}"
  mariadb-password: "${MARIADB_PASS}"
  wp-admin-password: "${WP_ADMIN_PASS}"
  jwt-secret: "${JWT_SECRET}"
  wc-consumer-key: "${WC_CONSUMER_KEY}"
  wc-consumer-secret: "${WC_CONSUMER_SECRET}"
EOF

echo "✓ Production secret manifest successfully generated at: ${OUTPUT_FILE}"
echo "  To apply to Kubernetes cluster:"
echo "    kubectl apply -f ${OUTPUT_FILE}"
echo "======================================================="
